import type { MapYaml } from "./map-schema";

/**
 * Generate keyd.conf body (no [ids] if caller wraps — we include full file).
 * super_as_command: swap Left/Right Alt with Super so Super sits under thumb like Cmd on many Mac layouts.
 */
export function compileKeydConf(map: MapYaml): string {
  const lines: string[] = ["# Generated by OneRing — edit config/keyboard/map.yaml", ""];

  lines.push("[ids]", "*", "");

  lines.push("[main]");
  if (map.super_as_command) {
    lines.push("# super_as_command: swap Alt and Meta (tune to your keyboard)");
    lines.push("leftalt = leftmeta");
    lines.push("leftmeta = leftalt");
    lines.push("rightalt = rightmeta");
    lines.push("rightmeta = rightalt");
  }

  for (const line of map.keyd_extra) {
    lines.push(line);
  }

  if (lines[lines.length - 1] !== "") lines.push("");
  return lines.join("\n");
}
